def load_feature_metadata():

    print_header(
        "LOADING FEATURE METADATA"
    )

    ensure_file(
        FEATURE_METADATA_PATH,
        "Feature metadata",
    )

    with open(
        FEATURE_METADATA_PATH,
        "r",
        encoding="utf-8",
    ) as f:

        metadata = json.load(f)

    if "features" not in metadata:

        raise ValueError(
            "feature_metadata.json tidak memiliki "
            "key 'features'."
        )

    features = metadata["features"]

    if not isinstance(
        features,
        list,
    ):

        raise ValueError(
            "metadata['features'] harus berupa list."
        )

    if len(features) != 96:

        raise ValueError(
            f"Jumlah feature metadata salah. "
            f"Ditemukan {len(features)}, "
            f"diharapkan 96."
        )

    for i, item in enumerate(features):

        if not isinstance(
            item,
            dict,
        ):

            raise ValueError(
                f"Metadata index {i} "
                f"bukan dictionary."
            )

        required_keys = [
            "index",
            "sensor_id",
            "approach",
            "lane_id",
            "feature",
        ]

        for key in required_keys:

            if key not in item:

                raise ValueError(
                    f"Metadata index {i} "
                    f"tidak memiliki '{key}'."
                )

        if item["index"] != i:

            raise ValueError(
                f"Index metadata tidak sesuai. "
                f"Expected {i}, "
                f"got {item['index']}."
            )

    sensor_ids = sorted(
        list(
            set(
                item["sensor_id"]
                for item in features
            )
        )
    )

    print(
        f"[INFO] Feature count : "
        f"{len(features)}"
    )

    print(
        f"[INFO] Sensor count  : "
        f"{len(sensor_ids)}"
    )

    print(
        f"[INFO] Sensor IDs    : "
        f"{sensor_ids}"
    )

    print(
        "[OK] Feature metadata validation passed."
    )

    return features


