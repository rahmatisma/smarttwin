def calculate_metrics(
    y_true,
    y_pred,
):

    true_flat = y_true.reshape(
        -1
    )

    pred_flat = y_pred.reshape(
        -1
    )

    mse = mean_squared_error(
        true_flat,
        pred_flat,
    )

    rmse = np.sqrt(
        mse
    )

    mae = mean_absolute_error(
        true_flat,
        pred_flat,
    )

    return {
        "mae": float(mae),
        "rmse": float(rmse),
        "mse": float(mse),
    }


