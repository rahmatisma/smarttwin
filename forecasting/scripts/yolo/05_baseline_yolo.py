# PER FEATURE COMPARISON
# ======================================================================

def evaluate_per_feature(
    y_true,
    lstm_pred,
    baseline_pred,
    metadata,
):

    print_header(
        "COMPARISON PER TRAFFIC FEATURE"
    )

    rows = []

    for feature in FEATURES:

        indices = [
            i
            for i, item in enumerate(
                metadata
            )
            if item["feature"] == feature
        ]

        if not indices:
            continue

        true_values = y_true[
            :,
            indices
        ]

        lstm_values = lstm_pred[
            :,
            indices
        ]

        baseline_values = baseline_pred[
            :,
            indices
        ]

        true_flat = true_values.reshape(
            -1
        )

        lstm_flat = lstm_values.reshape(
            -1
        )

        baseline_flat = baseline_values.reshape(
            -1
        )

        lstm_mae = mean_absolute_error(
            true_flat,
            lstm_flat,
        )

        lstm_mse = mean_squared_error(
            true_flat,
            lstm_flat,
        )

        lstm_rmse = np.sqrt(
            lstm_mse
        )

        baseline_mae = mean_absolute_error(
            true_flat,
            baseline_flat,
        )

        baseline_mse = mean_squared_error(
            true_flat,
            baseline_flat,
        )

        baseline_rmse = np.sqrt(
            baseline_mse
        )

        mae_improvement = calculate_improvement(
            baseline_mae,
            lstm_mae,
        )

        rmse_improvement = calculate_improvement(
            baseline_rmse,
            lstm_rmse,
        )

        rows.append(
            {
                "feature": feature,
                "lstm_mae": float(lstm_mae),
                "lstm_rmse": float(lstm_rmse),
                "lstm_mse": float(lstm_mse),
                "persistence_mae": float(
                    baseline_mae
                ),
                "persistence_rmse": float(
                    baseline_rmse
                ),
                "persistence_mse": float(
                    baseline_mse
                ),
                "mae_improvement_percent": mae_improvement,
                "rmse_improvement_percent": rmse_improvement,
                "feature_count": len(indices),
            }
        )

    df = pd.DataFrame(
        rows
    )

    print()

    print(
        df.to_string(
            index=False,
            float_format=lambda x: f"{x:.6f}",
        )
    )

    return df


