def validate_data(
    X_test,
    y_test,
    config,
):

    print_header(
        "VALIDATING TEST DATA"
    )

    # --------------------------------------------------------------
    # NaN / Inf
    # --------------------------------------------------------------

    x_nan = int(
        np.isnan(X_test).sum()
    )

    x_inf = int(
        np.isinf(X_test).sum()
    )

    y_nan = int(
        np.isnan(y_test).sum()
    )

    y_inf = int(
        np.isinf(y_test).sum()
    )

    print(
        f"[INFO] X_test | NaN: "
        f"{x_nan} | Inf: {x_inf}"
    )

    print(
        f"[INFO] y_test | NaN: "
        f"{y_nan} | Inf: {y_inf}"
    )

    if x_nan > 0 or x_inf > 0:

        raise ValueError(
            "X_test mengandung NaN atau Inf."
        )

    if y_nan > 0 or y_inf > 0:

        raise ValueError(
            "y_test mengandung NaN atau Inf."
        )

    # --------------------------------------------------------------
    # Dimensions
    # --------------------------------------------------------------

    if X_test.ndim != 3:

        raise ValueError(
            f"X_test harus 3D. "
            f"Ditemukan {X_test.ndim}D."
        )

    if y_test.ndim != 2:

        raise ValueError(
            f"y_test harus 2D. "
            f"Ditemukan {y_test.ndim}D."
        )

    expected_input_size = int(
        config["input_size"]
    )

    expected_output_size = int(
        config["output_size"]
    )

    if X_test.shape[2] != expected_input_size:

        raise ValueError(
            f"Input size mismatch.\n"
            f"Config : {expected_input_size}\n"
            f"X_test: {X_test.shape[2]}"
        )

    if y_test.shape[1] != expected_output_size:

        raise ValueError(
            f"Output size mismatch.\n"
            f"Config : {expected_output_size}\n"
            f"y_test: {y_test.shape[1]}"
        )

    if X_test.shape[0] != y_test.shape[0]:

        raise ValueError(
            "Jumlah sample X_test dan y_test "
            "tidak sama."
        )

    print(
        "[OK] Test dataset validation passed."
    )


