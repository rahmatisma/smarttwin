# GENERATE PERSISTENCE BASELINE
# ======================================================================

def generate_persistence_baseline(
    X_test,
):

    print_header(
        "GENERATING PERSISTENCE BASELINE"
    )

    """
    Persistence baseline:

        y_hat(t+1) = x(t)

    Karena X_test berbentuk:

        [sample, sequence_length, features]

    maka timestep terakhir:

        X_test[:, -1, :]

    digunakan sebagai prediksi untuk target berikutnya.
    """

    baseline_scaled = X_test[
        :,
        -1,
        :
    ].copy()

    print(
        f"[INFO] Baseline prediction shape : "
        f"{baseline_scaled.shape}"
    )

    if np.isnan(
        baseline_scaled
    ).any():

        raise ValueError(
            "Baseline prediction mengandung NaN."
        )

    if np.isinf(
        baseline_scaled
    ).any():

        raise ValueError(
            "Baseline prediction mengandung Inf."
        )

    print(
        "[INFO] Baseline method : Persistence"
    )

    print(
        "[INFO] Formula         : "
        "y(t+1) = y(t)"
    )

    print(
        "[OK] Persistence baseline generated."
    )

    return baseline_scaled


