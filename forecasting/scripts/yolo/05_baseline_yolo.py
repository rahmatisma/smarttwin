# ======================================================================

def save_final_report(
    config,
    scaled_metrics,
    original_metrics,
    feature_df,
    sensor_df,
):

    print_header(
        "SAVING BASELINE COMPARISON REPORT"
    )

    lstm_scaled = scaled_metrics[
        "lstm"
    ]

    persistence_scaled = scaled_metrics[
        "persistence"
    ]

    lstm_original = original_metrics[
        "lstm"
    ]

    persistence_original = original_metrics[
        "persistence"
    ]

    report = {

        "experiment": (
            "LSTM vs Persistence Baseline"
        ),

        "dataset": config.get(
            "dataset"
        ),

        "model": config.get(
            "model"
        ),

        "sequence_length": config.get(
            "sequence_length"
        ),

        "forecast_horizon": config.get(
            "forecast_horizon"
        ),

        "baseline": {
            "name": "Persistence",
            "definition": (
                "y(t+1) = y(t)"
            ),
        },

        "scaled_metrics": {

            "lstm": lstm_scaled,

            "persistence": persistence_scaled,

            "mae_improvement_percent": (
                calculate_improvement(
                    persistence_scaled["mae"],
                    lstm_scaled["mae"],
                )
            ),

            "rmse_improvement_percent": (
                calculate_improvement(
                    persistence_scaled["rmse"],
                    lstm_scaled["rmse"],
                )
            ),

            "mse_improvement_percent": (
                calculate_improvement(
                    persistence_scaled["mse"],
                    lstm_scaled["mse"],
                )
            ),
        },

        "original_scale_metrics": {

            "lstm": lstm_original,

            "persistence": persistence_original,

            "mae_improvement_percent": (
                calculate_improvement(
                    persistence_original["mae"],
                    lstm_original["mae"],
                )
            ),

            "rmse_improvement_percent": (
                calculate_improvement(
                    persistence_original["rmse"],
                    lstm_original["rmse"],
                )
            ),

            "mse_improvement_percent": (
                calculate_improvement(
                    persistence_original["mse"],
                    lstm_original["mse"],
                )
            ),
        },

        "feature_summary": {

            "best_lstm_improvement": (
                float(
                    feature_df[
                        "mae_improvement_percent"
                    ].max()
                )
                if not feature_df.empty
                else None
            ),

            "worst_lstm_improvement": (
                float(
                    feature_df[
                        "mae_improvement_percent"
                    ].min()
                )
                if not feature_df.empty
                else None
            ),

            "features_lstm_better": (
                int(
                    (
                        feature_df[
                            "mae_improvement_percent"
                        ]
                        > 0
                    ).sum()
                )
                if not feature_df.empty
                else 0
            ),

            "features_lstm_worse": (
                int(
                    (
                        feature_df[
                            "mae_improvement_percent"
                        ]
                        < 0
                    ).sum()
                )
                if not feature_df.empty
                else 0
            ),
        },

        "sensor_summary": {

            "best_lstm_improvement": (
                float(
                    sensor_df[
                        "mae_improvement_percent"
                    ].max()
                )
                if not sensor_df.empty
                else None
            ),

            "worst_lstm_improvement": (
                float(
                    sensor_df[
                        "mae_improvement_percent"
                    ].min()
                )
                if not sensor_df.empty
                else None
            ),

            "sensors_lstm_better": (
                int(
                    (
                        sensor_df[
                            "mae_improvement_percent"
                        ]
                        > 0
                    ).sum()
                )
                if not sensor_df.empty
                else 0
            ),

            "sensors_lstm_worse": (
                int(
                    (
                        sensor_df[
                            "mae_improvement_percent"
                        ]
                        < 0
                    ).sum()
                )
                if not sensor_df.empty
                else 0
            ),
        },

        "output_directory": str(
            BASELINE_DIR
        ),
    }

    output_path = (
        BASELINE_DIR
        / "baseline_comparison_report.json"
    )

    save_json(
        report,
        output_path,
    )

    print(
        f"[SAVED] {output_path}"
    )

    return report


