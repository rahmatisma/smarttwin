# IMPROVEMENT
# ======================================================================

def calculate_improvement(
    baseline_value,
    model_value,
):

    if baseline_value == 0:

        return None

    improvement = (
        (
            baseline_value
            - model_value
        )
        / baseline_value
    ) * 100.0

    return float(
        improvement
    )


