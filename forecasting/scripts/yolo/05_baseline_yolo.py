def plot_feature_comparison(
    feature_df,
):

    print_header(
        "PLOTTING FEATURE COMPARISON"
    )

    if feature_df.empty:
        return

    x = np.arange(
        len(feature_df)
    )

    width = 0.36

    plt.figure(
        figsize=(14, 7)
    )

    plt.bar(
        x - width / 2,
        feature_df[
            "lstm_mae"
        ],
        width,
        label="LSTM",
    )

    plt.bar(
        x + width / 2,
        feature_df[
            "persistence_mae"
        ],
        width,
        label="Persistence",
    )

    plt.xticks(
        x,
        feature_df[
            "feature"
        ],
        rotation=45,
        ha="right",
    )

    plt.xlabel(
        "Traffic Feature"
    )

    plt.ylabel(
        "MAE"
    )

    plt.title(
        "LSTM vs Persistence Baseline - MAE per Feature"
    )

    plt.legend()

    plt.grid(
        axis="y",
        alpha=0.3,
    )

    plt.tight_layout()

    output_path = (
        PLOT_DIR
        / "lstm_vs_persistence_mae_per_feature.png"
    )

    plt.savefig(
        output_path,
        dpi=200,
    )

    plt.close()

    print(
        f"[SAVED] {output_path}"
    )


