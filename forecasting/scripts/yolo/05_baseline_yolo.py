# MAIN
# ======================================================================

def main():

    print()
    print("=" * 70)
    print(
        "YOLO TRAFFIC LSTM "
        "BASELINE COMPARISON"
    )
    print("=" * 70)

    print(
        f"[INFO] Output directory : "
        f"{OUTPUT_DIR}"
    )

    print(
        f"[INFO] Baseline directory : "
        f"{BASELINE_DIR}"
    )

    # --------------------------------------------------------------
    # Load configuration
    # --------------------------------------------------------------

    config = load_training_config()

    # --------------------------------------------------------------
    # Load feature metadata
    # --------------------------------------------------------------

    metadata = load_feature_metadata()

    # --------------------------------------------------------------
    # Load test data
    # --------------------------------------------------------------

    (
        X_test,
        y_test,
    ) = load_test_data()

    # --------------------------------------------------------------
    # Validate test data
    # --------------------------------------------------------------

    validate_data(
        X_test,
        y_test,
        config,
    )

    # --------------------------------------------------------------
    # Load target scaler
    # --------------------------------------------------------------

    scaler = load_target_scaler()

    # --------------------------------------------------------------
    # Load LSTM predictions
    # --------------------------------------------------------------

    lstm_original = load_lstm_predictions()

    # --------------------------------------------------------------
    # Validate LSTM prediction shape
    # --------------------------------------------------------------

    if (
        lstm_original.shape
        != y_test.shape
    ):

        raise ValueError(
            "Shape LSTM prediction "
            "tidak sama dengan y_test.\n"
            f"LSTM : {lstm_original.shape}\n"
            f"y    : {y_test.shape}"
        )

    # --------------------------------------------------------------
    # Generate persistence baseline
    # --------------------------------------------------------------

    baseline_scaled = (
        generate_persistence_baseline(
            X_test
        )
    )

    # --------------------------------------------------------------
    # Scaled LSTM prediction
    # --------------------------------------------------------------

    lstm_scaled = scaler.transform(
        lstm_original
    )

    # --------------------------------------------------------------
    # Scaled metrics
    # --------------------------------------------------------------

    (
        lstm_scaled_metrics,
        persistence_scaled_metrics,
    ) = evaluate_scaled(
        y_test=y_test,
        lstm_scaled=lstm_scaled,
        baseline_scaled=baseline_scaled,
    )

    # --------------------------------------------------------------
    # Inverse transform
    # --------------------------------------------------------------

    (
        y_true_original,
        lstm_original_from_scaler,
        baseline_original,
    ) = inverse_transform(
        scaler=scaler,
        y_test=y_test,
        lstm_scaled=lstm_scaled,
        baseline_scaled=baseline_scaled,
    )

    # --------------------------------------------------------------
    # Check LSTM original prediction consistency
    # --------------------------------------------------------------

    lstm_difference = np.max(
        np.abs(
            lstm_original
            - lstm_original_from_scaler
        )
    )

    print(
        f"[INFO] LSTM inverse-transform "
        f"consistency max error : "
        f"{lstm_difference:.10f}"
    )

    # Use the already generated original-scale
    # LSTM prediction from evaluation.
    #
    # This avoids unnecessary changes caused by
    # transforming original predictions again.

    lstm_original_final = (
        lstm_original
    )

    # --------------------------------------------------------------
    # Original-scale metrics
    # --------------------------------------------------------------

    (
        lstm_original_metrics,
        persistence_original_metrics,
    ) = evaluate_original_scale(
        y_true=y_true_original,
        lstm_pred=lstm_original_final,
        baseline_pred=baseline_original,
    )

    # --------------------------------------------------------------
    # Per feature
    # --------------------------------------------------------------

    feature_df = evaluate_per_feature(
        y_true=y_true_original,
        lstm_pred=lstm_original_final,
        baseline_pred=baseline_original,
        metadata=metadata,
    )

    # --------------------------------------------------------------
    # Per sensor
    # --------------------------------------------------------------

    sensor_df = evaluate_per_sensor(
        y_true=y_true_original,
        lstm_pred=lstm_original_final,
        baseline_pred=baseline_original,
        metadata=metadata,
    )

    # --------------------------------------------------------------
    # Save predictions
    # --------------------------------------------------------------

    save_predictions(
        y_true=y_true_original,
        baseline_scaled=baseline_scaled,
        baseline_original=baseline_original,
    )

    # --------------------------------------------------------------
    # Save comparison tables
    # --------------------------------------------------------------

    save_comparison_csv(
        feature_df,
        sensor_df,
    )

    # --------------------------------------------------------------
    # Plots
    # --------------------------------------------------------------

    plot_feature_comparison(
        feature_df
    )

    plot_sensor_comparison(
        sensor_df
    )

    plot_improvement(
        feature_df
    )

    # --------------------------------------------------------------
    # Final report
    # --------------------------------------------------------------

    scaled_metrics = {
        "lstm": lstm_scaled_metrics,
        "persistence": persistence_scaled_metrics,
    }

    original_metrics = {
        "lstm": lstm_original_metrics,
        "persistence": persistence_original_metrics,
    }

    report = save_final_report(
        config=config,
        scaled_metrics=scaled_metrics,
        original_metrics=original_metrics,
        feature_df=feature_df,
        sensor_df=sensor_df,
    )

    # --------------------------------------------------------------
    # Final summary
    # --------------------------------------------------------------

    print_header(
        "BASELINE COMPARISON SUMMARY"
    )

    print()
    print(
        "[ORIGINAL SCALE]"
    )

    print()

    print(
        "LSTM"
    )

    print(
        f"MAE  : "
        f"{lstm_original_metrics['mae']:.6f}"
    )

    print(
        f"RMSE : "
        f"{lstm_original_metrics['rmse']:.6f}"
    )

    print(
        f"MSE  : "
        f"{lstm_original_metrics['mse']:.6f}"
    )

    print()

    print(
        "PERSISTENCE"
    )

    print(
        f"MAE  : "
        f"{persistence_original_metrics['mae']:.6f}"
    )

    print(
        f"RMSE : "
        f"{persistence_original_metrics['rmse']:.6f}"
    )

    print(
        f"MSE  : "
        f"{persistence_original_metrics['mse']:.6f}"
    )

    print()

    overall_mae_improvement = (
        calculate_improvement(
            persistence_original_metrics[
                "mae"
            ],
            lstm_original_metrics[
                "mae"
            ],
        )
    )

    overall_rmse_improvement = (
        calculate_improvement(
            persistence_original_metrics[
                "rmse"
            ],
            lstm_original_metrics[
                "rmse"
            ],
        )
    )

    print(
        "[LSTM IMPROVEMENT OVER PERSISTENCE]"
    )

    print(
        f"MAE improvement  : "
        f"{overall_mae_improvement:.2f}%"
        if overall_mae_improvement is not None
        else "MAE improvement  : N/A"
    )

    print(
        f"RMSE improvement : "
        f"{overall_rmse_improvement:.2f}%"
        if overall_rmse_improvement is not None
        else "RMSE improvement : N/A"
    )

    print()

    if (
        overall_mae_improvement is not None
        and overall_mae_improvement > 0
    ):

        print(
            "[RESULT] LSTM mengungguli "
            "Persistence berdasarkan MAE."
        )

    elif (
        overall_mae_improvement is not None
        and overall_mae_improvement < 0
    ):

        print(
            "[RESULT] Persistence lebih baik "
            "daripada LSTM berdasarkan MAE."
        )

    else:

        print(
            "[RESULT] LSTM dan Persistence "
            "memiliki MAE yang sama."
        )

    print()

    print(
        "[FEATURE SUMMARY]"
    )

    print(
        f"LSTM better : "
        f"{report['feature_summary']['features_lstm_better']}"
    )

    print(
        f"LSTM worse  : "
        f"{report['feature_summary']['features_lstm_worse']}"
    )

    print()

    print(
        "[OUTPUT]"
    )

    print(
        f"{BASELINE_DIR}"
    )

    print()

    print(
        "=" * 70
    )

    print(
        "BASELINE COMPARISON COMPLETED"
    )

    print(
        "=" * 70
    )


# ======================================================================
